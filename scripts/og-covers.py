"""JPEG twins of the guide covers for the share cards (components/OgImage/Article.vue).

Satori, which draws the share cards, can't read WebP. For every `cover:` in content/blog/*/*.md
this writes public/images/blog/og/<lang>/<name>.jpg (the top-left 1440x900 of the screenshot,
760x475) and lists them in data/og-covers.ts so a guide only asks for a twin that exists.

Usage: python -I scripts/og-covers.py
"""
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / 'public'
made = set()

for md in sorted((ROOT / 'content' / 'blog').glob('*/*.md')):
    m = re.search(r'^cover:\s*"?(/images/blog/demo/([^/]+)/([^"\s]+)\.webp)"?\s*$', md.read_text(encoding='utf8'), re.M)
    if not m:
        continue
    src = PUBLIC / m.group(1).lstrip('/')
    if not src.exists():
        print(f'missing cover {m.group(1)} in {md.relative_to(ROOT)}', file=sys.stderr)
        continue
    rel = f'/images/blog/og/{m.group(2)}/{m.group(3)}.jpg'
    out = PUBLIC / rel.lstrip('/')
    if rel not in made and (not out.exists() or out.stat().st_mtime < src.stat().st_mtime):
        out.parent.mkdir(parents=True, exist_ok=True)
        img = Image.open(src).convert('RGB')
        w, h = img.size
        # Same 16:10 frame as the card, from the top left where the page header is
        crop_w = min(w, round(h * 1.6))
        img = img.crop((0, 0, crop_w, min(h, round(crop_w / 1.6))))
        img.resize((760, 475), Image.LANCZOS).save(out, 'JPEG', quality=80, optimize=True, progressive=True)
        print('wrote', rel)
    made.add(rel)

lines = ',\n'.join(f"  '{p}'" for p in sorted(made))
(ROOT / 'data' / 'og-covers.ts').write_text(
    '// Generated by scripts/og-covers.py: JPEG twins of the guide covers that exist under public/\n'
    f'export const OG_COVERS = new Set<string>([\n{lines}\n])\n',
    encoding='utf8', newline='\n')
print(f'{len(made)} cover twins')
